#!/usr/bin/env node
'use strict';

/**
 * Lists the licences of every package the app and backend ship with, and
 * flags copyleft ones that could affect a proprietary release.
 *
 *   node scripts/third-party-licenses.js
 *
 * Writes THIRD_PARTY_NOTICES.md at the repo root. Zero dependencies: it walks
 * node_modules from each package's production dependency tree.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|SSPL|OSL|CC-BY-SA)\b/i;

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

function licenseOf(pkg) {
  if (!pkg) return 'UNKNOWN';
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && pkg.license.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type || l).join(' OR ');
  return 'UNKNOWN';
}

/** Resolves a dependency the way Node does: nearest node_modules upwards. */
function resolvePkgDir(name, fromDir, projectRoot) {
  let dir = fromDir;
  while (dir.startsWith(projectRoot)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

function collect(projectDir) {
  const rootPkg = readJson(path.join(projectDir, 'package.json'));
  if (!rootPkg) return new Map();
  const seen = new Map();
  const queue = Object.keys(rootPkg.dependencies || {}).map((n) => ({ name: n, from: projectDir }));
  while (queue.length) {
    const { name, from } = queue.shift();
    const dir = resolvePkgDir(name, from, projectDir);
    if (!dir || seen.has(dir)) continue;
    const pkg = readJson(path.join(dir, 'package.json'));
    seen.set(dir, { name: pkg?.name || name, version: pkg?.version || '?', license: licenseOf(pkg) });
    for (const dep of Object.keys(pkg?.dependencies || {})) queue.push({ name: dep, from: dir });
  }
  return seen;
}

const projects = ['app', 'backend'].filter((p) => fs.existsSync(path.join(ROOT, p, 'node_modules')));
const all = new Map();
for (const p of projects) {
  for (const info of collect(path.join(ROOT, p)).values()) all.set(`${info.name}@${info.version}`, info);
}

const rows = [...all.values()].sort((a, b) => a.name.localeCompare(b.name));
const flagged = rows.filter((r) => COPYLEFT.test(r.license) || r.license === 'UNKNOWN');
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;

const out = [
  '# Third-party notices',
  '',
  `Generated by \`scripts/third-party-licenses.js\` from the production dependencies of: ${projects.join(', ')}.`,
  '',
  '## Licence summary',
  '',
  ...Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([l, n]) => `- ${l}: ${n}`),
  '',
  '## Needs review',
  '',
  flagged.length
    ? flagged.map((r) => `- ${r.name}@${r.version}: ${r.license}`).join('\n')
    : 'None. No copyleft or unknown licences in the shipped dependency tree.',
  '',
  '## All packages',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
];

fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
console.log(`${rows.length} packages; ${flagged.length} need review. Wrote THIRD_PARTY_NOTICES.md`);
for (const r of flagged) console.log(`  review: ${r.name}@${r.version} (${r.license})`);
